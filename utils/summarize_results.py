import os
import pandas as pd
import json
import plotly.express as px
import plotly.graph_objects as go

class SolarResultsAnalyzer:
    def __init__(self, results_file):
        self.results_file = results_file
        self.distances = None
        self.results_df = None

    def load_results(self):
        """
        Load the results from the CSV file generated by SunLocalizer.

        Attributes:
            results_df (pd.DataFrame): The loaded results dataframe.
            distances (pd.Series): The series of distances in miles.
        """
        self.results_df = pd.read_csv(self.results_file)
        self.distances = self.results_df["distance_miles"]

    def calculate_statistics(self):
        """
        Calculate summary statistics from the loaded results.

        Returns
        -------
        stats (dict): A dictionary containing the following statistics:
            mean (float): The mean distance in miles.
            median (float): The median distance in miles.
            mode (float): The most common distance in miles.
            std (float): The standard deviation of the distances in miles.
            variance (float): The variance of the distances in miles.
            min (dict): A dictionary with the minimum distance and the location of that distance.
            max (dict): A dictionary with the maximum distance and the location of that distance.
            percentiles (dict): A dictionary with the percentiles of the distances at 
                [0.1, 0.25, 0.5, 0.75, 0.9, 0.95].
            percent_below_thresholds (dict): A dictionary with the percentage of distances 
            below each of the given thresholds.
        """
        distances = self.distances
        stats = {
            "mean": distances.mean(),
            "median": distances.median(),
            "mode": distances.mode()[0],
            "std": distances.std(),
            "variance": distances.var(),
            "min": {
                "distance": distances.min(),
                "location": self.results_df.loc[distances.idxmin()]["location"]
            },
            "max": {
                "distance": distances.max(),
                "location": self.results_df.loc[distances.idxmax()]["location"]
            },
            "percentiles": distances.quantile([0.1, 0.25, 0.5, 0.75, 0.9, 0.95]).to_dict(),
            "percent_below_thresholds (meters)": {t: float((distances < t).mean() * 100) 
                                                  for t in [1, 10, 50, 100, 1000, 
                                                            3000, 5000, 10000, 25000, 50000]},
        }
        return stats

    def save_json(self, summary_dict, file_path):
        """
        Save a JSON file containing a summary of the results.

        Parameters
        ----------
        summary_dict (dict): A dictionary containing the summary statistics.

        Notes
        -----
        The file is saved in a directory named "results" in the current working directory.
        The filename is "summary.json".
        """
        json_file = file_path
        with open(json_file, "w") as f:
            json.dump(summary_dict, f, indent=4)

    def summarize(self, file_path):
        """Run the full analysis: load, calculate stats, save JSON, and plot."""
        self.load_results()
        stats = self.calculate_statistics()
        self.save_json(stats, file_path)
